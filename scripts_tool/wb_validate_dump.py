# -*- coding: utf-8 -*-
import json, os
BASE_DIR = r'C:\Users\GravMix\.gemini\antigravity\playground\core-pulsar'
DUMP = os.path.join(BASE_DIR, 'data_dump', 'wb_cards_seo_dump.json')
VAL_DIR = os.path.join(BASE_DIR, 'validation_report')
os.makedirs(VAL_DIR, exist_ok=True)
print("╔══════════════════════════════════════════════════════════════╗")
print("║  ГЛУБОКАЯ ПРОВЕРКА ОШИБОК WB (из дампа)                      ║")
print("╚══════════════════════════════════════════════════════════════╝\n")
with open(DUMP, 'r', encoding='utf-8') as f:
    cards = json.load(f)
print(f"✓ Загружено карточек: {len(cards)}\n")
issues = {'long50':[],'no_brand':[],'wrong_brand':[],'zero_dims':[],'no_weight':[],'low_rating':[],'few_photos':[],'no_desc':[]}
for c in cards:
    nm = c.get('nmID')
    t = c.get('title','')
    if len(t) > 50: issues['long50'].append({'nm':nm,'title':t,'len':len(t)})
    b = c.get('brand','')
    if not b: issues['no_brand'].append(nm)
    elif b.lower().strip() not in ['gravmix','гравмикс']: issues['wrong_brand'].append({'nm':nm,'brand':b})
    d = c.get('dimensions',{})
    if d.get('width',0)==0 or d.get('height',0)==0 or d.get('length',0)==0: issues['zero_dims'].append({'nm':nm})
    chs = c.get('characteristics',[])
    if not any(ch.get('id')==14177450 for ch in chs): issues['no_weight'].append(nm)
    r = c.get('rating',0)
    if r>0 and r<4.0: issues['low_rating'].append({'nm':nm,'r':r,'vc':c.get('vendorCode')})
    ps = c.get('photos',[])
    if len(ps)<4: issues['few_photos'].append({'nm':nm,'cnt':len(ps)})
    desc = c.get('description','')
    if len(desc)<100: issues['no_desc'].append(nm)
print("🔴 КРИТИЧЕСКИЕ ПРОБЛЕМЫ (по стратегическому документу):")
print(f"  1. Заголовки >50 символов: {len(issues['long50'])} (лимит 50, не 60!)")
print(f"  2. Рейтинг <4.0 (КЛОНИРОВАТЬ!): {len(issues['low_rating'])}")
print(f"  3. Нулевые габариты: {len(issues['zero_dims'])}")
print(f"  4. Нет веса (char 14177450): {len(issues['no_weight'])}")
print(f"\n🟡 ВАЖНЫЕ ПРОБЛЕМЫ:")
print(f"  5. Неправильный бренд: {len(issues['wrong_brand'])}")
print(f"  6. Нет бренда: {len(issues['no_brand'])}")
print(f"  7. Мало фото (<4): {len(issues['few_photos'])}")
print(f"\n⚠️ ПРОЧИЕ:")
print(f"  8. Короткие описания: {len(issues['no_desc'])}\n")
if issues['low_rating']:
    print("═"*70)
    print("🎯 КАРТОЧКИ ДЛЯ КЛОНИРОВАНИЯ (рейтинг <4.0):")
    print("═"*70)
    for i in sorted(issues['low_rating'], key=lambda x: x['r'])[:20]:
        print(f"  NM_{i['nm']:10} | {i['vc']:25} | Рейтинг: {i['r']:.2f}")
    print()
if issues['long50']:
    print("═"*70)
    print("📏 ЗАГОЛОВКИ >50 СИМВОЛОВ (требуют сокращения!):")
    print("═"*70)
    for i in issues['long50'][:10]:
        print(f"  NM_{i['nm']} ({i['len']} символов)")
        print(f"     {i['title']}")
        print()
if issues['zero_dims']:
    print(f"⚠️ Карточек с нулевыми габаритами: {len(issues['zero_dims'])}")
    print(f"   Примеры: {', '.join('NM_'+str(nm) for nm in list(issues['zero_dims'])[:10])}\n")
rep = {'total':len(cards),'issues':{k:len(v) for k,v in issues.items()},'details':issues}
with open(os.path.join(VAL_DIR,'wb_validation_detailed.json'),'w',encoding='utf-8') as f:
    json.dump(rep,f,ensure_ascii=False,indent=2)
print("═"*70)
print("🚨 ПРИОРИТЕТЫ ДЕЙСТВИЙ:")
print("═"*70)
print(f"PHASE 1: Техническая чистка")
print(f"  [ ] 1. Сократить {len(issues['long50'])} заголовков до 50 символов")
print(f"  [ ] 2. Исправить {len(issues['zero_dims'])} нулевых габаритов")
print(f"  [ ] 3. Добавить вес для {len(issues['no_weight'])} карточек")
print(f"  [ ] 4. Привести бренд к 'GravMix' ({len(issues['wrong_brand'])} карточек)")
print(f"\nPHASE 2: Репутационный менеджмент")
print(f"  [ ] 5. КЛОНИРОВАТЬ {len(issues['low_rating'])} карточек с рейтингом <4.0")
print(f"\nPHASE 3: Контентная оптимизация")
print(f"  [ ] 6. Добавить фото для {len(issues['few_photos'])} карточек (минимум 4)")
print(f"  [ ] 7. Расширить {len(issues['no_desc'])} описаний\n")
print(f"✓ Детальный отчет: validation_report/wb_validation_detailed.json")
